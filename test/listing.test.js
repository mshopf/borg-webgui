const { test } = require ('node:test');
const assert = require ('node:assert/strict');
const fs = require ('node:fs');
const { JSDOM } = require ('jsdom');

const html = fs.readFileSync (require.resolve ('../public/listing.html'), 'utf8');
const script = fs.readFileSync (require.resolve ('../public/listing.js'), 'utf8');
const settle = async () => { for (let i = 0; i < 20; i++) await new Promise (resolve => { setImmediate (resolve); }); };

test ('backup-first selection, paging, lazy directories, special names and restore', async t => {
    const dom = new JSDOM (html, { url: 'http://localhost/listing.html?backup=test&view=archive', runScripts: 'outside-only' });
    t.after (() => dom.window.close ());
    const { window } = dom;
    const requests = [];
    window.confirm = () => true;
    window.fetch = async (url, options) => {
        requests.push ([url, options]);
        let data;
        if (url === '/api/status') data = {};
        else if (url.startsWith ('/api/archives/')) data = [null, '2024-01-01-120000', '2024-01-02-120000'];
        else if (url.startsWith ('/api/restore/')) data = 'handle';
        else if (url.includes ('/dir%20%23%3F')) data = { c: { 'inside': { s: 2 } }, next: null };
        else if (url.includes ('cursor=7')) data = { c: { 'other': { s: 3 } }, next: null };
        else if (url.includes ('archive=')) data = { c: { '/dir #?': { c: null, C: 2, S: 5 }, 'file': { s: 1 } }, next: 7 };
        else data = { c: { 'history': { a: [-1, 2], s: 3 } } };
        return { ok: true, json: async () => data };
    };
    window.eval (script);
    await settle ();
    const doc = window.document;
    assert.equal (doc.querySelector ('#archive').value, '2');
    assert.equal (doc.querySelector ('#archive').options.length, 2);
    assert.equal (doc.querySelector ('#archive-picker').hidden, false);
    assert.equal (doc.querySelector ('.entry span').textContent, '');
    doc.querySelector ('.path.dir').click ();
    await settle ();
    assert.ok (requests.some (([url]) => url.includes ('/dir%20%23%3F?archive=2')));
    doc.querySelector ('#root > ul > li:nth-child(2) > .entry').click ();
    assert.equal (doc.querySelector ('#button').disabled, false);
    doc.querySelector ('#root > ul > li:nth-child(2) > .entry').click ();
    assert.equal (doc.querySelector ('#button').disabled, true);
    doc.querySelector ('#root > .more').click ();
    await settle ();
    assert.equal (doc.querySelector ('#root > .more'), null);
    assert.equal (doc.querySelectorAll ('#root > ul > li').length, 3);
    doc.querySelector ('#root > ul > li:nth-child(2) > .entry').click ();
    doc.querySelector ('#button').click ();
    await settle ();
    const restore = requests.find (([url]) => url.startsWith ('/api/restore/'));
    assert.deepEqual (JSON.parse (restore[1].body), { archive: '2024-01-02-120000', list: ['file'] });
    doc.querySelector ('#archive').value = '1';
    doc.querySelector ('#archive').dispatchEvent (new window.Event ('change'));
    await settle ();
    assert.equal (doc.querySelector ('#button').disabled, true);
    doc.querySelector ('#view').value = 'files';
    doc.querySelector ('#view').dispatchEvent (new window.Event ('change'));
    await settle ();
    assert.equal (doc.querySelector ('#archive-picker').hidden, true);
    assert.ok (doc.querySelector ('.entry span').textContent.length > 0);
});
