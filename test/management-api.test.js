const { test } = require ('node:test');
const assert = require ('node:assert/strict');
const fs = require ('node:fs/promises');
const path = require ('node:path');
const os = require ('node:os');
const express = require ('express');
const argon2 = require ('argon2');
const { ManagementStore } = require ('../dist/management-store');
const { BackupService } = require ('../dist/backup-runtime');
const { AccessControl, protectMutation } = require ('../dist/access-control');
const { managementRouter } = require ('../dist/management-api');

test ('admin CRUD enforces grants, revision conflicts, CSRF protection and secret redaction', { timeout: 30000 }, async t => {
    const dir = await fs.mkdtemp (path.join (os.tmpdir (), 'borg-admin-api-'));
    t.after (() => fs.rm (dir, { recursive: true, force: true }));
    const password = 'long-test-password';
    const store = await ManagementStore.open (path.join (dir, 'etc'), { auth: { admin: { pwd: await argon2.hash (password) } } });
    const service = await BackupService.open (store, path.join (dir, 'var'), async () => 0);
    const access = new AccessControl (store); const app = express ();
    app.use (express.json ());
    app.use ('/api', (req, res, next) => { void access.authenticate (req, res, next).catch (next); });
    app.use ('/api', protectMutation);
    app.use ('/api/admin', managementRouter (store, service, access, async () => {}, () => ['legacy']));
    app.use ((error, _req, res, _next) => { res.status (error.name === 'ZodError' ? 400 : error.status ?? 500).json ({ error: error.message }); });
    const server = app.listen (0); await new Promise (resolve => { server.once ('listening', resolve); });
    t.after (async () => { await service.stop (); server.closeAllConnections (); await new Promise (resolve => { server.close (resolve); }); });
    const url = 'http://127.0.0.1:' + server.address ().port;
    const auth = user => 'Basic ' + Buffer.from (user + ':' + password).toString ('base64');
    const call = (route, method = 'GET', body, user = 'admin', extra = {}) => fetch (url + '/api/admin' + route, { method,
        headers: { Authorization: auth (user), 'Content-Type': 'application/json', 'X-Borg-Admin': '1', ...extra }, body: body === undefined ? undefined : JSON.stringify (body) });
    const config = async () => (await call ('/configuration')).json ();
    assert.equal ((await fetch (url + '/api/admin/configuration')).status, 401);
    assert.equal ((await call ('/credentials/key', 'PUT', {}, 'admin', { Origin: 'https://evil.example' })).status, 403);
    assert.equal ((await call ('/credentials/key', 'PUT', {}, 'admin', { 'X-Borg-Admin': '' })).status, 403);
    let revision = (await config ()).revision;
    assert.equal ((await call ('/credentials/key', 'PUT', { revision, credential: { id: 'key', name: 'Key', passphrase: 'sensitive-repo-secret' } })).status, 200);
    const publicConfig = await config ();
    assert.equal (JSON.stringify (publicConfig).includes ('sensitive-repo-secret'), false);
    assert.equal (JSON.stringify (publicConfig).includes ('$argon2'), false);
    assert.equal (publicConfig.credentials[0].hasPassphrase, true);
    assert.equal ((await call ('/backups/job', 'PUT', { revision, backup: {} })).status, 400);
    revision = publicConfig.revision;
    const backup = { id: 'job', name: 'Job', mode: 'local', repository: '/backup/repo', sources: ['/home'], credentialId: 'key', index: false };
    assert.equal ((await call ('/backups/job', 'PUT', { revision, backup })).status, 200);
    assert.equal ((await call ('/backups/job', 'PUT', { revision, backup })).status, 409);
    revision = (await config ()).revision;
    const user = { id: 'reader', password, enabled: true, admin: false, grants: [{ backup: 'job', browse: true, restore: false, run: false }] };
    assert.equal ((await call ('/users/reader', 'PUT', { revision, user })).status, 200);
    assert.equal ((await call ('/configuration', 'GET', undefined, 'reader')).status, 403);
    assert.equal ((await call ('/backups/job/run', 'POST', {}, 'reader')).status, 403);
    assert.equal ((await (await call ('/backups', 'GET', undefined, 'reader')).json ()).backups.length, 1);
    assert.equal ((await call ('/users/admin', 'DELETE', { revision: (await config ()).revision })).status, 409);
    assert.equal ((await call ('/credentials/key', 'DELETE', { revision: (await config ()).revision })).status, 400);
    const run = await (await call ('/backups/job/run', 'POST', {})).json ();
    await service.idle ();
    assert.equal (service.runs ().find (item => item.id === run.id).state, 'done');
    assert.equal ((await (await call ('/runs', 'GET', undefined, 'reader')).json ()).length, 0);
    assert.equal ((await call ('/runs/' + run.id + '/log', 'GET', undefined, 'reader')).status, 403);
    revision = (await config ()).revision;
    assert.equal ((await call ('/users/reader', 'PUT', { revision, user: { ...user, password: undefined, enabled: false } })).status, 200);
    assert.equal ((await call ('/backups', 'GET', undefined, 'reader')).status, 401);
    assert.equal ((await call ('/backups/job', 'DELETE', { revision: (await config ()).revision })).status, 200);
    assert.equal ((await config ()).backups.length, 0);
});
